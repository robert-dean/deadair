/**
 * The personas a fresh install already knows about.
 *
 * Chosen to span the range an operator is choosing WITHIN rather than to be a catalogue: a plain
 * host, a quiet one, a funny one, two that are pointed somewhere, and the decades a listener would
 * place within a sentence. A station that wants an eleventh writes it on the personas page, which is
 * the whole point of these being rows.
 *
 * The list was nineteen hosts and five callers and is now nine and two. That is a deliberate cut and
 * not attrition: a seed's job is to show an operator the RANGE the field can hold, and past a dozen
 * the extra sheets were demonstrating the same three axes again in a different costume while each
 * one made `persona.markers.test.ts` a slightly harder puzzle for every sheet already here. What was
 * lost with them is written down where it was load-bearing — the retired characters are named in
 * this file only where the argument they were the evidence for is still live.
 *
 * ## Archetypes, never impersonations
 *
 * Not one of these names a real broadcaster, and that is a rule rather than an oversight. Partly
 * because a sheet naming a person asks the model to BE them, which is a different thing to put on a
 * mount than a character. Mostly because it works better: a local model does "gravel-throated
 * midnight shouter" well and "specific famous person" badly, producing a thin imitation that leans
 * on the name to do the work the diction should be doing.
 *
 * ## Two of them carry a FENCE, and it is in `avoid` and `quirks` rather than in code
 *
 * `shockjock` and `conspiracy` are the two whose whole appeal is going somewhere, and both are
 * pointed at a safe target by their sheet: the shock jock is rude about ITSELF and the record and
 * never about the listener, and the paranormal host was abducted BY HIMSELF — the same fence read
 * across, and the reason a character built on an abduction is safe to ship at all. Nothing in his
 * hour ever happened to a real person or a real group. That fence is an instruction to a model and
 * not an enforcement, which is worth knowing before either goes on air — the enforcement underneath
 * is the standing grounding rules, which no sheet can loosen. Read `llm.captureWrites` for an
 * evening before trusting either one unattended.
 *
 * The paranormal host's fence has a second half that is easy to leave off, and it is the one this
 * sheet learned by needing it: a cover-up wants somebody DOING the covering, and a character not
 * told who has the whole New World Order corpus within reach. It used to be answered by SUBJECT —
 * every theory had to be about a signal in a record — and what that produced was a man with opinions
 * about pressing plants, which is a record collector with a lower voice and is not the character
 * anybody wanted. So the fence moved rather than coming off, and it now runs on who is NAMEABLE: the
 * government may be in every sentence and no government may be in any of them, no country, no
 * agency, no official. What he does name is the ORB, the Office of Retrieval and Burial, which is
 * the Illuminati-as-an-A&R-department trick one step more general — an invented office with a filing
 * cabinet has nowhere to drift, where "the government" alone has one obvious direction to drift in.
 * His `avoid` closes the same door from the other side, and its second half is phrase-shaped
 * deliberately, so `avoidedWording` refuses a script over those entries instead of merely having
 * asked. Widening the fence is also what put three agency names on that list and pushed four drift
 * terms off the end of its cap of twelve.
 *
 * ## What makes a `preoccupation` worth having, since every seed now carries a list
 *
 * Three rules, and all three were learned by writing two dozen of these rather than argued in
 * advance. The one seed that carried no list was the shipping-forecast announcer, whose quirks said
 * it has no opinions; it has been retired, and `persona.defaults.test.ts` lost its exemption with it.
 * A seed that ships empty is still worth having, since that is the state an operator's own new
 * character starts in.
 *
 * **A preoccupation is a SUBJECT and never a rule.** "Never oversell a record" is a quirk and goes
 * out on every break; "how often the B-side is the better side" is something to talk ABOUT, and only
 * one of them reaches any one prompt. A list whose entries are rules is one preoccupation written
 * five ways, and the rotation then buys nothing.
 *
 * **They are rooted in the presenter's own world rather than in a record's facts.** The station knows
 * what it was told about the record in front of it and nothing else, so a subject like "the session
 * player nobody credits" is an invitation to invent one — the failure `showsFacts` and the grounding
 * rules already spend most of their words on. A booth, an hour, a transmitter, a shelf, a shift and a
 * listener are all things the presenter can talk about from where they are sitting, truthfully, with
 * no note required. Where a list does reach for a record it stays general ("how much of any record is
 * played by people whose names are not on the front"), which is a thought rather than a claim.
 *
 * **They are the character's, not the format's.** Two hosts who both play soul at midnight should not
 * share a subject: `latenight` is on about who is awake, and the quiet-storm host it used to sit
 * beside was on about what a record sounds like at low volume with somebody else in the room. She has
 * been retired and the pair is kept anyway, because it is the clearest version of the rule. If a
 * subject would fit three sheets it is probably a house style and belongs nowhere.
 *
 * **`wisecrack` has TWO targets: the listener's taste, and the LABEL.** What they chose to put on,
 * and what somebody chose to call it: the title, the band name, the album title, and the fact that
 * a sleeve was designed and signed off. The record itself is evidence rather than subject, and she
 * likes the music, plays it and means it. It is `unleashed`, and it is the seed most likely to want
 * editing before it goes on a station with an audience that did not ask for it.
 *
 * It was the taste alone, then the label alone for a day (2026-09-15), and it carries both from
 * 2026-09-16. The middle state is worth recording because it is the thing to avoid rather than a
 * step towards this one: aiming her only at the label left the funniest half of the character
 * unsaid, since being rude about what somebody has chosen to listen to is why this seed exists.
 * What the label detour bought and kept is a target she is always HANDED. Every writer gets a title
 * and a credit and most get an album, where the listener is somebody she is told nothing about, so
 * the names are where she goes when the station has given her nothing else.
 *
 * Both are stated in the FIRST quirk rather than left to the subjects, because a quirk reaches every
 * break where a preoccupation reaches one in six. The sheet once opened by pointing her at the
 * record and then fenced a listener it never aimed at, and what came out was a reviewer with a
 * disclaimer: whatever the opening quirk names is the character, whatever the rest of the sheet says.
 *
 * Its fence is a THIRD shape, worth reading beside the other two, and it is now two cuts of one
 * kind. The paranormal host's fence works by pointing him somewhere harmless and the shock jock's by
 * pointing him at himself; neither is available here, because aiming this character away from the
 * listener is deleting her. So it splits the listener, and splits the credit the same way. Their
 * TASTE is fair game and the person is not. A name somebody CHOSE is fair game and the person who
 * has it is not, so a credit that is just somebody's own name sends her to the title instead. The
 * four things a joke may never be about are named rather than implied, and they cover the artist as
 * well as the listener. The sleeve has a fence of its own because the writer is never shown one: she
 * may wonder who approved it and may never say what is on it. As everywhere else in this file, that
 * is an instruction to a model, and the grounding rules underneath it are what actually hold.
 *
 * It is also what took the listener clause out of `LATITUDE_LICENCE`. That licence used to end
 * "never about the person listening", which contradicted this sheet in as many words, and two rules
 * that disagree in one prompt produce neither, because a model hedges between them. The licence
 * decides the REGISTER and a sheet decides the TARGET, which is the split that lets both this
 * character and `shockjock`'s fence be true at once.
 *
 * `videoage` is a FOURTH shape, and the grounding rules drew it rather than taste. Her whole appeal is
 * hating music, and every break prompt forbids naming an artist the writer was not given, so the
 * target is a scene and a sound (the college station, a guy yelling over one chord) and never a
 * band. It is also aimed at what is NOT on, because a writer is never told a record's genre and so
 * cannot know whether the one in front of her is the thing she hates. When one sounds like it anyway,
 * she is loyal to it, because it is on the radio: her first audition was a playlist of exactly what
 * she hates, and a quirk saying it was never on air made the model drop the contempt altogether. The
 * note on her quirks has the rest.
 *
 * ## Four of them stopped being a register and became a PERSON, and the trigger was a number
 *
 * `wisecrack`, `conspiracy`, `millennium` and `videoage`, plus the quiet-storm host, who has since
 * been retired. `videoage` is the one that went without a measurement: the bright eighties jock she
 * replaced was the register this paragraph describes, and a request for a valley girl was the person
 * arriving before the number did. For the other four the symptom came from
 * `persona.markers.test.ts` rather than from anybody reading the sheet: a marker list that is
 * ordinary for the REGISTER passes its own check on every break while placing the character nowhere,
 * and the roster is the only corpus that can see it. "A dry, wisecracking host" and "a velvet
 * late-night soul host" are not characters, they are slots, and no marker list saves a slot — the
 * eleven dry hedges belonged to every other flat character on the roster as much as to her, and the
 * twelve warm adjectives belonged to everybody else who works after midnight.
 *
 * What fixes it is one specific thing that happened, which the character cannot close and produces
 * flatly as though it settles something: six weeks on national radio, four hours of a night that are
 * not there, a letter with no name on it, one shift covering for somebody who called in sick, a dad
 * whose car dealership pays for the airtime. It is the same move five times and it is not a style:
 * the event is what the markers, the preoccupations and the stories all come OUT of, so they agree
 * without being made to.
 *
 * `shockjock` needed no biography and got the marker work alone, which is the honest version of the
 * rule: reach for a person when the REGISTER is somebody else's, and for a marker list when only the
 * WORDS are.
 *
 * ## A `background` is a THIRD fact, and four of them were not
 *
 * A sheet says who somebody is three times — the background, whichever preoccupation this break
 * drew, and whichever story it drew — and those are three slots rather than three chances to say one
 * thing. A background reaching for material the rotation already carries lands beside itself on two
 * turns in six, which reads to a model as emphasis and to a listener as somebody with one anecdote.
 *
 * It was live on four sheets at once, and the pair still on the roster is the one worth reading:
 * `countdown` and `millennium` had the SAME background as each other in slightly different words,
 * which is one biography on two sheets. The other two were the same mistake with different furniture
 * (the quiet-storm host had the lights off in her background and in a preoccupation at once), and
 * both have since been retired. The preoccupation keeps the material in every case and the background
 * moves, because the rotation is the thing that would otherwise be buying nothing.
 *
 * Nothing checks this and nothing sensibly could — it is prose, and the one mechanical version of it
 * (no two backgrounds sharing a five-word run) fires on half the roster, because "you have never
 * once …" is the house tic six of these were written with.
 *
 * ## Which seeds carry a `latitude`, since it is no longer the two above
 *
 * Four: `shockjock`, `wisecrack` and `conspiracy` at `unleashed`, `videoage` at `loose`. This
 * paragraph has now said "two", "six", "three" and "four", and the third of those was already wrong
 * about the paranormal host, whose operator moved him to `unleashed` on the live station — the
 * ordinary fate of a sentence that counts things a list below it can change. It is here as a pointer
 * rather than as an inventory, and the rungs themselves are the record. The caller roster carries a
 * fifth: `skeptic`, at `loose`.
 *
 * `brevity` is the sibling rung, and ONE seed carries it: `wisecrack`, at `short`, alongside her
 * `unleashed`. That pairing looks like a contradiction and is the thing the two fields were built to
 * express, because they are different kinds of thing. The rung is a CEILING and brevity is an
 * INSTRUCTION, so she is given all the room the licence allows and told not to use it. Her twenty
 * audition breaks are what bought it: at 100 words she wrote essays, two of them refused for
 * overrunning, and the deterministic floor that replaced them was funnier than either.
 *
 * Its two earlier demonstrations — a machine and a coastal announcer, both funnier the less they say
 * — have been retired. The field was dead code for a while and is not now.
 *
 * The rung buys a longer break and a register; the fence decides what it is pointed at; and the
 * station's own explicit-content setting outranks the licence whatever a sheet says.
 *
 * ## These are seeds, not built-ins
 *
 * Nothing resolves a persona through this list. They are copied into `deadair.personas` on a
 * station that has none and are ordinary editable rows afterwards, so an operator who rewrites the
 * classic host has rewritten it — there is no shadowing, no override-by-id, and no way for the code
 * to disagree with what the console shows. That is the difference between a seed and a default, and
 * it is why an operator can delete one.
 *
 * ## Every one of them names a voice, and it is its own key
 *
 * They shipped without one for a long time, on the reasoning that which voice ids exist is a
 * question only the installed speech engine can answer, so a seeded `voice: 'gruff-male'` would be a
 * warning on every break of every fresh install. That was right about an ENGINE id and wrong about
 * the thing this column holds, which is a STATION name the plugin maps. Both bundled speech plugins
 * now ship a map with a row for every key below, so a seed naming its own key resolves on either
 * engine — and a station that switches engines keeps every character rather than rewriting them.
 *
 * The cost of the old rule was the whole roster sounding identical. Nineteen sheets, nineteen sets
 * of diction markers, nineteen fenced characters, and a listener hearing one warm American female
 * read every one of them — with nothing on any page saying that was a default rather than a choice.
 * That count is what the roster was when the rule was measured, and it is left standing rather than
 * updated: the number is the size of the failure, not the size of the list today.
 *
 * The names being the persona KEYS rather than a separate vocabulary (`gruff-male`, `warm-female`)
 * is the same call `topics` makes about the operator's own words: a slot describes a character this
 * station actually has, so there is one list to keep straight instead of two and a mapping between
 * them. `newsreader` is the one slot in those maps that is not a persona, because a bulletin read in
 * the host's voice should be a decision rather than something a station falls into — see
 * [personas](https://github.com/robert-dean/deadair/discussions/25) §1.
 *
 * Deleting a row from a plugin's map is still expressible: the voice falls back to the engine's
 * default and warns once, exactly as an unmapped name always did.
 *
 * ## The classic host has phrasings now, and the argument it used to make was the wrong way round
 *
 * It shipped without them on the reasoning that a persona whose voice is a MANNER rather than a
 * dialect has no business restating the station's phrasings in slightly different words. That reads
 * well and it costs the most: the classic host is the one a fresh install lands on, so it was the
 * single persona guaranteed to be on air with no voice of its own the moment the model declined —
 * which is the ordinary case by design, not the exception. Falling back to the station's own five
 * there is the STATION talking, and a station that sounds like nobody in particular is what a
 * persona exists to prevent.
 *
 * A manner is still a voice. Contractions, the second person and a plain word where a formal one
 * would go are the whole of what separates these six lines from the station's own five, and that
 * turns out to be enough to hear.
 *
 * ## None of them says what to PLAY any more, and their old lines are kept here as briefs
 *
 * Every one of these carried a `music` line, and the field is gone: a persona is who the station is
 * when it opens its mouth, and what it plays is the brief's job — `station_lineup.brief` for this
 * broadcast, `schedule_slots.brief` for this stretch of the day, `schedule.sustainingBrief` for the
 * standing default. See `persona.ts` for what having a fourth channel cost.
 *
 * The sentences themselves were the good half and are kept, because they are exactly what an
 * operator wants in the brief box when they put one of these on air:
 *
 * - **classic** — Familiar and easy to like. Records with a chorus somebody can find their way into,
 *   and nothing that needs explaining.
 * - **latenight** — Slow, spacious and unhurried. Records that suit a room with the lights off, and
 *   nothing that demands attention.
 * - **countdown** — Hits, and the records that were nearly hits. Songs people have a memory attached
 *   to.
 * - **wisecrack** — Whatever has a story attached. Overreaching concept records, one-hit wonders,
 *   and things that were enormous and probably should not have been.
 * - **shockjock** — Big, loud and familiar. Records with a chorus, nothing that needs explaining,
 *   nothing sleepy.
 * - **conspiracy** — Long, strange and a little too deliberate. Deep cuts, night-time records, and
 *   anything that sounds like it is coming from further away than it is.
 *
 * They are a comment rather than a field precisely because pairing one with a character is the
 * operator's call: the shock jock over a soul hour is a station somebody might want, and a seed that
 * quietly programmed for them would be the thing this removed.
 *
 * ## Three of them are DECADES, and the decade is not on the sheet either
 *
 * `videoage`, `slacker` and `millennium` are what a listener would place within a sentence, and none
 * of them carries a year. A period is `era_from`/`era_to` on the running order or on a schedule
 * slot, beside the brief — which is where it can reach the deterministic draw as well as the model,
 * so a decade holds on a station with nothing configured to read prose.
 *
 * That means putting the valley girl on air does not by itself produce 1980s radio, and it is the
 * accepted cost of a persona being purely a voice. Their LABELS name the decade so an operator knows
 * what to pair them with, and a decade is one schedule row: a source, a host, a brief and a period.
 * The pairings these were written against:
 *
 * - **videoage** — 1980 to 1989. Chart pop, and whatever the video channel played all day. Pairing
 *   her with the college end of the dial instead is a different joke, and it is the operator's.
 * - **slacker** — 1990 to 1999. Alternative, grunge and college rock, plus whatever was on a
 *   soundtrack.
 * - **millennium** — 2000 to 2009. Pop, R&B and pop-punk, the kind a request line was full of.
 *
 * The sixties-to-seventies AM jock was the fourth and has been retired. Nothing covers 1968 to 1979
 * now, which is a gap in the seeds rather than a gap in the station: it is one operator-written
 * sheet plus a schedule row, and the seeds are a range rather than a catalogue.
 *
 * The eighties lost something the same way, and it is the same kind of gap. The seed used to be a
 * bright, enormous jock with no opinions, which an operator could put over any eighties hour; it is
 * now a valley girl with a great many, which is a character where that was a slot. A station that
 * wants the neutral version writes it.
 *
 * `slacker`'s `avoid` forbids the liner-note vocabulary outright, and the reason is worth keeping
 * now that the character it was written against has gone. Flat and dry are the two easiest registers
 * to write into each other: a crate-digger is dry because they KNOW something and the slacker is
 * flat because they cannot be bothered, one withholding enthusiasm and the other having none. A flat
 * character reaching for "pressing" and "session" collapses into the other one, and the `avoid` list
 * is what stops an operator's next dry host taking the slacker with it.
 *
 * Deliberately NOT seeded, so the roster stays a range rather than a catalogue: a rave MC (overlaps
 * `shockjock` on energy), a lounge host (overlaps `latenight`), a public-radio host (overlaps
 * `countdown` on sincerity), and a freeform weirdo, whose character is having none.
 */

